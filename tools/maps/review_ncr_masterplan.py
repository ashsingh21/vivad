#!/usr/bin/env python3
"""Render the design atlas and check its interactive preview; never starts Vivad."""
import argparse
import json
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("preview", type=Path, help="Standalone preview generated by the visualization renderer")
    args = parser.parse_args()
    review = ROOT / "build/ncr-masterplan-review"
    review.mkdir(parents=True, exist_ok=True)
    errors, widths = [], []
    ids = [p["id"] for p in json.loads((ROOT / "docs/ncr/masterplan/ncr-4km.plan.json").read_text())["pois"]]
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page(viewport={"width":1600, "height":1310}, device_scale_factor=1)
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.goto((ROOT / "docs/ncr/masterplan/ncr-4km-atlas.svg").as_uri())
        page.locator("svg").screenshot(path=str(ROOT / "docs/ncr/masterplan/ncr-4km-atlas.png"))
        for width in [320, 736, 1024]:
            page.set_viewport_size({"width":width, "height":1500})
            page.goto(args.preview.resolve().as_uri())
            frame = page.frame_locator("iframe")
            frame.locator(".ncr-map svg").wait_for()
            for poi in ids:
                frame.locator("#ncr-location").select_option(poi)
                assert frame.locator(f'[data-selected-poi="{poi}"]').count() == 1, poi
                assert frame.locator("#ncr-location-detail").inner_text().startswith(poi), poi
            frame.locator("#ncr-location").select_option("D1")
            dimensions = frame.locator("#ncr-masterplan").evaluate('''(el) => ({
                width: el.clientWidth,
                scroll: el.scrollWidth,
                marks: el.querySelectorAll(".ncr-map svg rect").length,
                labels: Array.from(el.querySelectorAll(".ncr-map svg text")).map(x => {
                    const b=x.getBoundingClientRect();
                    return {text:x.textContent, x:b.x, right:b.right, y:b.y, height:b.height};
                })
            })''')
            assert dimensions["scroll"] <= dimensions["width"] + 1, dimensions
            assert dimensions["marks"] > 400, dimensions
            frame.locator("#ncr-masterplan").screenshot(path=str(review / f"inline-{width}.png"))
            widths.append({"viewport":width, "width":dimensions["width"], "scroll":dimensions["scroll"], "marks":dimensions["marks"]})
        page.emulate_media(color_scheme="dark")
        page.set_viewport_size({"width":736, "height":1500})
        page.goto(args.preview.resolve().as_uri())
        page.frame_locator("iframe").locator("#ncr-masterplan").screenshot(path=str(review / "inline-dark.png"))
        browser.close()
    assert not errors, errors
    result = {"passed":True, "selection_checks":48, "viewport_widths":widths, "javascript_errors":errors,
              "game_launched":False, "fps_measured":False}
    (review / "visual-review.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
